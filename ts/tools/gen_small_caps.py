"""Generate ts/src/smallCaps.ts from confusables.small_capitals().

The Python table derives Latin small capitals from Unicode character names, which
JavaScript has no access to. The derived code points are emitted as data; the
hand-written part of the fold table is ported by hand in confusables.ts and the
two are checked against the Python table by the parity test.

Run from anywhere: python3 ts/tools/gen_small_caps.py
"""

from __future__ import annotations

import pathlib
import sys
import unicodedata

TS_DIR = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(TS_DIR.parent))

import confusables  # noqa: E402

OUT = TS_DIR / "src" / "smallCaps.ts"


def main() -> int:
    caps = sorted(confusables.small_capitals().items())
    if len(caps) < 20:
        print("unexpected small capital count; refusing to write", file=sys.stderr)
        return 1
    lines = [
        "// Generated by tools/gen_small_caps.py. Do not edit by hand.",
        f"// Source: Unicode {unicodedata.unidata_version} character names (LATIN LETTER SMALL CAPITAL x).",
        "",
        "/** Code point -> ASCII lower-case letter. */",
        "export const SMALL_CAPITALS: ReadonlyArray<readonly [number, string]> = [",
    ]
    lines += [f"  [0x{cp:04x}, {letter!r}]," .replace("'", '"') for cp, letter in caps]
    lines += ["];", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} entries={len(caps)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
