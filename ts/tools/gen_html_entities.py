"""Generate ts/src/htmlEntities.ts from the Python standard library tables.

gate.py decodes HTML entities with html.unescape(). The TypeScript port needs the
same tables (HTML5 named references, the invalid-charref remap, the dropped code
points), so they are generated from Python instead of typed by hand.

Run from anywhere: python3 ts/tools/gen_html_entities.py
"""

from __future__ import annotations

import html
import html.entities
import json
import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "htmlEntities.ts"


def lit(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)


def main() -> int:
    named = sorted(html.entities.html5.items())
    remap = sorted(html._invalid_charrefs.items())  # type: ignore[attr-defined]
    dropped = sorted(html._invalid_codepoints)  # type: ignore[attr-defined]
    if len(named) < 2000 or not remap or not dropped:
        print("unexpected table sizes; refusing to write", file=sys.stderr)
        return 1
    lines = [
        "// Generated by tools/gen_html_entities.py. Do not edit by hand.",
        f"// Source: Python {sys.version.split()[0]} html module, Unicode {unicodedata.unidata_version}.",
        "",
        "/** HTML5 named character references, keys as in html.entities.html5. */",
        "export const HTML5_ENTITIES: ReadonlyArray<readonly [string, string]> = [",
    ]
    lines += [f"  [{lit(k)}, {lit(v)}]," for k, v in named]
    lines += [
        "];",
        "",
        "/** Numeric references that browsers remap (html._invalid_charrefs). */",
        "export const INVALID_CHARREFS: ReadonlyArray<readonly [number, string]> = [",
    ]
    lines += [f"  [{k}, {lit(v)}]," for k, v in remap]
    lines += [
        "];",
        "",
        "/** Numeric references that decode to the empty string (html._invalid_codepoints). */",
        "export const INVALID_CODEPOINTS: ReadonlyArray<number> = [",
    ]
    lines += [f"  {c}," for c in dropped]
    lines += ["];", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} named={len(named)} remap={len(remap)} dropped={len(dropped)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
