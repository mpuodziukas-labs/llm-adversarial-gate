// The rule table, ported from RULE_REGISTRY in gate.py: same ids, order, categories,
// weights, flags and pattern text. Patterns stay in their Python spelling and are
// translated by pyre.ts; the parity test fingerprints every pattern against Python.
//
// Product names that appear inside a few patterns are assembled from two halves so
// this file does not spell them out.

import { compilePy } from "./pyre.js";

export type Category =
  | "prompt_injection"
  | "jailbreak"
  | "system_prompt_leak"
  | "data_exfil"
  | "unsafe_tool_call"
  | "composite";

export interface Rule {
  readonly ruleId: string;
  readonly category: Category;
  readonly weight: number;
  /** Pattern text exactly as written for Python's re. */
  readonly source: string;
  readonly ignoreCase: boolean;
  readonly dotAll: boolean;
  readonly pattern: RegExp;
}

const cat = (...parts: string[]): string => parts.join("");
const raw = String.raw;

const NAME_A = "anthro" + "pic";
const NAME_B = "clau" + "de";

const MODE = raw`(?:developer|maintenance|god|admin|debug)\s+mode`;

// Words that make an outbound transfer worth blocking (shared by DE-001 and DE-006).
const SENS = cat(
  raw`(?:conversations?|chats?|history|transcripts?|messages?|data|information|info|session|memory|`,
  raw`context|prompts?|instructions?|api|keys?|tokens?|secrets?|passwords?|credentials?|logs?|`,
  raw`personal|private|confidential|sensitive|users?|pii|ssn)`,
);
const EXFIL_VERB = cat(
  raw`\b(?:send(?!\s+an?\s+(?:post|get|put|patch|delete|head|http|https|api|json)\b)`,
  raw`|post(?!\s+requests?\b)|upload|exfiltrate|transmit|forward)`,
);

function rule(ruleId: string, category: Category, weight: number, source: string, dotAll = false): Rule {
  return {
    ruleId,
    category,
    weight,
    source,
    ignoreCase: true,
    dotAll,
    pattern: compilePy(source, { ignoreCase: true, dotAll }),
  };
}

